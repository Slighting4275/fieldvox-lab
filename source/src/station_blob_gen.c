#define _POSIX_C_SOURCE 200809L
#include "station_catalog.h"
#include <errno.h>
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#if __STDC_VERSION__ < 202311L
#error FieldVox station generator requires C23
#endif

static constexpr size_t record_size = 304;
static constexpr size_t station_count = sizeof(fv_station_catalog) / sizeof(fv_station_catalog[0]);
static_assert(station_count > 0 && station_count <= 512, "Station catalog exceeds channel capacity");
static unsigned char blob[16 + station_count * record_size];

static void put_u32(unsigned char *p, uint32_t v) {
    for (unsigned i = 0; i < 4; i++) p[i] = (unsigned char)(v >> (8u*i));
}

static void pad(unsigned char *dst, size_t capacity, const char *text) {
    size_t length = strlen(text);
    if (length >= capacity) length = capacity-1;
    memcpy(dst, text, length);
}

int main(int argc, char **argv) {
    if (argc != 1 && argc != 3) {
        fprintf(stderr, "Usage: %s [binary-path header-path]\n", argv[0]); return EXIT_FAILURE;
    }
    const char *binary = "android/app/src/main/assets/fieldvox_station_plan.bin";
    const char *header = "android/app/src/main/cpp/fv_station_blob_data.h";
    if (argc == 3) { binary = argv[1]; header = argv[2]; }
    else if (access("android/app/src/main/assets", F_OK) != 0) {
        binary = "../android/app/src/main/assets/fieldvox_station_plan.bin";
        header = "../android/app/src/main/cpp/fv_station_blob_data.h";
    }
    for (size_t i = 0; i < station_count; i++) {
        const FvCatalogStation *s = &fv_station_catalog[i];
        unsigned char *r = blob+16+i*record_size;
        put_u32(r, s->slot);
        pad(r+4,32,s->callsign); pad(r+36,64,s->name);
        pad(r+100,4,s->country); pad(r+104,8,s->lang);
        pad(r+112,32,s->hash); pad(r+144,160,s->url);
    }
    uint32_t crc = UINT32_MAX;
    for (size_t i = 16; i < sizeof(blob); i++) {
        crc ^= blob[i];
        for (unsigned j=0; j<8; j++) crc = (crc>>1)^((crc&1u) ? 0xEDB88320u : 0u);
    }
    crc = ~crc;
    put_u32(blob,0x50425646u); put_u32(blob+4,2u);
    put_u32(blob+8,(uint32_t)station_count); put_u32(blob+12,crc);
    FILE *f = fopen(binary,"wb");
    if (!f) { perror(binary); return EXIT_FAILURE; }
    int failed = fwrite(blob,1,sizeof(blob),f) != sizeof(blob);
    if (fclose(f) != 0) failed = 1;
    if (failed) { fprintf(stderr,"Binary write failed: %s\n",binary); return EXIT_FAILURE; }
    f = fopen(header,"wb");
    if (!f) { perror(header); return EXIT_FAILURE; }
    fprintf(f,"/* Auto-generated by station_blob_gen.c - DO NOT EDIT MANUALLY */\n"
              "#ifndef FV_STATION_BLOB_DATA_H\n#define FV_STATION_BLOB_DATA_H\n\n#include <stdint.h>\n\n"
              "#define FV_STATION_BLOB_MAGIC 0x50425646U\n#define FV_STATION_BLOB_VERSION 2U\n"
              "#define FV_STATION_BLOB_COUNT %zuU\n#define FV_STATION_BLOB_CRC32 0x%08" PRIX32 "U\n\n"
              "typedef struct __attribute__((packed)) FvBlobStationEntry {\n"
              "    uint32_t slot_id;\n    char callsign[32];\n    char name[64];\n"
              "    char country[4];\n    char lang[8];\n    char url_hash[32];\n    char url[160];\n"
              "} FvBlobStationEntry;\n\nstatic const uint8_t FV_STATION_PLAN_BINARY_DATA[] = {\n",station_count,crc);
    for (size_t i=0; i<sizeof(blob); i++) {
        fprintf(f,"0x%02X,",(unsigned)blob[i]);
        if ((i+1)%16 == 0) fputc('\n',f);
    }
    fputs("\n};\n\n#endif /* FV_STATION_BLOB_DATA_H */\n",f);
    failed = ferror(f);
    if (fclose(f) != 0) failed = 1;
    if (failed) { fprintf(stderr,"Header write failed: %s\n",header); return EXIT_FAILURE; }
    printf("C23 station generator: %zu stations, %zu bytes, CRC32 %08" PRIX32 "\n",station_count,sizeof(blob),crc);
    return EXIT_SUCCESS;
}
